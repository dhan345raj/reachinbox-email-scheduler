import { Worker, Job } from 'bullmq';
import nodemailer from 'nodemailer';
import { EMAIL_QUEUE_NAME, EmailJobData } from '../config/queue';
import { redisOptions } from '../config/redis';
import { config } from '../config';
import prisma from '../config/database';
import { rateLimitService } from '../services/rateLimit.service';
import { slackService } from '../services/slack.service';
import { elasticsearchService } from '../services/elasticsearch.service';
import { queueService } from '../services/queue.service';

/**
 * Processes a single email job from BullMQ
 */
export async function processEmailJob(job: Job<EmailJobData>): Promise<void> {
  const { emailId } = job.data;
  console.log(`[EmailWorker] Processing job ${job.id} for email ${emailId}`);

  // Fetch email and related sender, batch, and user models
  const email = await prisma.email.findUnique({
    where: { id: emailId },
    include: {
      sender: true,
      batch: true,
      user: true,
    },
  });

  if (!email) {
    console.warn(`[EmailWorker] Email ${emailId} not found in database. Skipping.`);
    return;
  }

  // 1. Idempotency check: Skip if already sent
  if (email.status === 'SENT') {
    console.log(`[EmailWorker] Email ${emailId} already marked as SENT. Skipping execution.`);
    return;
  }

  try {
    // 2. Check rate limit for this sender
    const hourlyLimit = email.batch?.hourlyLimit || config.rateLimit.maxEmailsPerHour;
    const rateLimit = await rateLimitService.checkRateLimit(email.senderId, hourlyLimit);

    if (!rateLimit.allowed) {
      console.warn(
        `[EmailWorker] Rate limit exceeded for sender ${email.sender.email} (${rateLimit.currentCount}/${hourlyLimit}). Rescheduling.`
      );

      // Calculate the start of the next hour window
      const nextWindow = rateLimitService.getNextAvailableWindow();
      const delayMs = Math.max(1000, nextWindow.getTime() - Date.now());

      // Update email status and scheduledAt in DB
      await prisma.email.update({
        where: { id: email.id },
        data: {
          status: 'RATE_LIMITED',
          scheduledAt: nextWindow,
        },
      });

      // Reschedule new delayed job for the next window
      const newJob = await queueService.addEmailJob(email.id, delayMs);

      await prisma.email.update({
        where: { id: email.id },
        data: {
          bullmqJobId: String(newJob.id),
        },
      });

      // Send alert to user's Slack if connected
      await slackService.sendRateLimitNotification(
        email.userId,
        email.senderId,
        email.sender.email,
        rateLimit.currentCount,
        hourlyLimit
      );

      return;
    }

    // 3. Mark as SENDING in DB
    await prisma.email.update({
      where: { id: email.id },
      data: { status: 'SENDING' },
    });

    // 4. Create Nodemailer transporter with Ethereal SMTP credentials
    const transporter = nodemailer.createTransport({
      host: 'smtp.ethereal.email',
      port: 587,
      secure: false,
      auth: {
        user: email.sender.etherealUser,
        pass: email.sender.etherealPass,
      },
    });

    // 5. Send email via Nodemailer
    const sendResult = await transporter.sendMail({
      from: `"${email.user.name}" <${email.sender.email}>`,
      to: email.recipient,
      subject: email.subject,
      text: email.body,
      html: email.body.replace(/\n/g, '<br/>'),
    });

    // 6. Extract test preview URL generated by Ethereal
    const testUrl = nodemailer.getTestMessageUrl(sendResult);
    const etherealUrl = testUrl ? String(testUrl) : null;
    const sentAt = new Date();

    console.log(`[EmailWorker] Email sent to ${email.recipient}! Preview URL: ${etherealUrl}`);

    // 7. Update status to SENT in DB
    const updatedEmail = await prisma.email.update({
      where: { id: email.id },
      data: {
        status: 'SENT',
        sentAt,
        etherealUrl,
        errorMessage: null,
      },
      include: {
        sender: true,
        batch: true,
        user: true,
      },
    });

    // 8. Check if the entire batch has finished
    const remainingPendingEmails = await prisma.email.count({
      where: {
        batchId: email.batchId,
        status: {
          in: ['SCHEDULED', 'RATE_LIMITED', 'SENDING'],
        },
      },
    });

    if (remainingPendingEmails === 0) {
      await prisma.batch.update({
        where: { id: email.batchId },
        data: { status: 'COMPLETED' },
      });
      console.log(`[EmailWorker] Batch ${email.batchId} marked as COMPLETED.`);
    }

    // 9. Index the sent email in Elasticsearch (non-blocking, non-fatal)
    try {
      await elasticsearchService.indexEmail(updatedEmail);
    } catch (esError) {
      console.error('[EmailWorker] Elasticsearch indexing failed (non-fatal):', esError);
    }
  } catch (error: any) {
    console.error(`[EmailWorker] Error processing email ${emailId}:`, error.message || error);

    // Only mark as FAILED if the email wasn't already sent
    const currentEmail = await prisma.email.findUnique({ where: { id: emailId } });
    if (currentEmail && currentEmail.status !== 'SENT') {
      await prisma.email.update({
        where: { id: emailId },
        data: {
          status: 'FAILED',
          errorMessage: error.message || 'Unknown sending error',
        },
      });
    }

    throw error;
  }
}

// BullMQ Worker instance
export const emailWorker = new Worker<EmailJobData>(
  EMAIL_QUEUE_NAME,
  async (job: Job<EmailJobData>) => {
    await processEmailJob(job);
  },
  {
    connection: redisOptions,
    concurrency: config.worker.concurrency,
  }
);

emailWorker.on('completed', (job: Job<EmailJobData>) => {
  console.log(`[EmailWorker] Job ${job.id} (email: ${job.data.emailId}) completed successfully.`);
});

emailWorker.on('failed', (job: Job<EmailJobData> | undefined, err: Error) => {
  console.error(`[EmailWorker] Job ${job?.id} failed with error:`, err.message);
});

emailWorker.on('error', (err: Error) => {
  console.error('[EmailWorker] Worker connection error:', err.message);
});

/**
 * Starts the worker and restores any orphaned jobs on startup
 */
export async function startEmailWorker(): Promise<Worker<EmailJobData>> {
  console.log(`[EmailWorker] Worker started with concurrency: ${config.worker.concurrency}`);

  // Restore any pending jobs persisted in PostgreSQL
  try {
    await queueService.restoreJobsOnStartup();
  } catch (restoreErr: any) {
    console.error('[EmailWorker] Failed restoring jobs on startup:', restoreErr.message || restoreErr);
  }

  return emailWorker;
}

export async function stopEmailWorker(): Promise<void> {
  console.log('[EmailWorker] Shutting down worker...');
  await emailWorker.close();
}

export default emailWorker;
